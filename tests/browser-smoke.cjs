const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const dir = path.resolve('tmp/ui');
  fs.mkdirSync(dir, { recursive: true });
  await page.goto('http://127.0.0.1:8787');
  await page.getByRole('button', { name: /实验复现/ }).click();
  await page.getByRole('heading', { name: '实验复现', exact: true }).waitFor();
  await page.getByRole('button', { name: '新建项目', exact: true }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('流程示例 · 特征标准化');
  await page.getByLabel('研究问题', { exact: true }).fill('特征标准化是否改变Iris分类实验的Accuracy和Macro F1？');
  await page.getByRole('button', { name: '创建项目', exact: true }).click();
  await page.locator('.breadcrumb b').filter({ hasText: '流程示例 · 特征标准化' }).waitFor();
  await page.getByRole('button', { name: '载入示例说明', exact: true }).click();
  await page.getByText('示例研究说明已载入', { exact: true }).waitFor();
  await page.getByRole('button', { name: '开始真实运行', exact: true }).click();
  await page.locator('.badge.succeeded').first().waitFor({ timeout: 45000 });
  await page.locator('.metric-row').waitFor();
  await page.screenshot({ path: path.join(dir, 'desktop-results.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '实验准备', exact: true }).click();
  await page.getByLabel('启用特征标准化', { exact: false }).uncheck();
  await page.getByRole('button', { name: '开始真实运行', exact: true }).click();
  await page.locator('.badge.succeeded').nth(1).waitFor({ timeout: 45000 });
  await page.getByRole('checkbox', { name: '将标准化特征 · 原方案加入比较', exact: true }).check();
  await page.getByRole('checkbox', { name: '将关闭标准化 · 变体加入比较', exact: true }).check();
  if (await page.locator('.compare-section tbody tr').count() !== 2) throw new Error('比较表没有两条实验');
  await page.getByRole('button', { name: /文献与开题/ }).click();
  await page.getByRole('button', { name: '文献比较', exact: true }).click();
  await page.getByRole('button', { name: '整理比较条目', exact: true }).click();
  await page.getByText('比较条目已整理，请逐项核对原文', { exact: true }).waitFor();
  await page.locator('.source-link').first().click();
  await page.locator('.source-panel').waitFor();
  await page.getByRole('button', { name: '关闭原文', exact: true }).click();
  await page.getByRole('button', { name: '修订并核对', exact: false }).click();
  await page.getByRole('button', { name: '保存核对', exact: true }).click();
  await page.getByText('已人工核对', { exact: true }).waitFor();
  await page.getByRole('button', { name: '问题与证据', exact: true }).click();
  await page.getByLabel('你想核对的问题').fill('数据集Iris的评价指标 Accuracy Macro F1');
  await page.getByRole('button', { name: '查找证据', exact: true }).click();
  await page.locator('.evidence-list article').first().waitFor();
  await page.screenshot({ path: path.join(dir, 'desktop-evidence.png'), fullPage: true });
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', { name: '导出开题准备材料', exact: true }).click();
  const download = await downloadEvent;
  await download.saveAs(path.join(dir, 'proposal-evidence.md'));
  if (!fs.readFileSync(path.join(dir, 'proposal-evidence.md'), 'utf8').includes('第1页')) throw new Error('导出缺少来源页码');
  for (const title of ['成果同步', '数据分析']) {
    await page.getByRole('button', { name: new RegExp(title) }).click();
    await page.getByRole('heading', { name: title === '成果同步' ? '成果同步' : '数据分析', exact: true }).waitFor();
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '展开导航', exact: true }).click();
  await page.getByRole('button', { name: /实验复现/ }).click();
  await page.locator('.sidebar.open').waitFor({ state: 'hidden' });
  await page.getByRole('heading', { name: '实验复现', exact: true }).waitFor();
  await page.screenshot({ path: path.join(dir, 'mobile-reproduce.png'), fullPage: true, animations: 'disabled' });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow) throw new Error('手机页面存在整体横向溢出');
  await page.getByRole('button', { name: '展开导航', exact: true }).click();
  await page.getByRole('button', { name: /文献与开题/ }).click();
  await page.locator('.sidebar.open').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '文献比较', exact: true }).click();
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('手机比较表未局部滚动');
  await page.screenshot({ path: path.join(dir, 'mobile-matrix.png'), fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '打开设置', exact: true }).click();
  await page.locator('dialog').waitFor();
  await page.keyboard.press('Escape');
  if (await page.locator('dialog').count()) throw new Error('设置弹窗无法通过Escape关闭');
  const report = { passed: true, desktop: '1440 × 1000', mobile: '390 × 844', pageErrors: errors, checked: ['项目创建', '真实实验两次', '实验比较', '文献比较与核对', '原文定位', '证据检索', '导出', '两个新模块入口', '手机导航与溢出', 'Escape关闭弹窗'] };
  fs.writeFileSync(path.join(dir, 'report.json'), JSON.stringify(report, null, 2));
  if (errors.length) throw new Error(errors.join('\n'));
  console.log(JSON.stringify(report));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
